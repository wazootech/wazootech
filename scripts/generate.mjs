#!/usr/bin/env node
// Generates REPOS.md and VERSION.md. Never hand-edit the output.
//
//   node scripts/generate.mjs           rewrite both files
//   node scripts/generate.mjs --check   exit 0 either way; drift is a tracked
//                                       state (the drift issue owns it), and
//                                       a nonzero exit means THIS RADAR broke
//
// Exit codes:  0 = current, or stale-but-tracked   1 = crashed
//              2 = cannot read the organization
//
// The "2" case matters. A token scoped to this repository alone cannot see the
// rest of the organization, and without the preflight below that would be
// reported as 52 missing repositories — a false alarm that would train everyone
// to ignore this job. Fail loudly instead.
// Design note: this records only facts that change RARELY — repository name,
// description, archive status, published package version. It deliberately does
// not record commit SHAs or last-push dates: those change constantly, which
// would make --check fail daily and train everyone to ignore the signal.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OWNER = "wazootech";
const MAP_VERSION = "0.1.0";

/**
 * Tier 1 is the curated showcase in README.md. It is maintained BY HAND on
 * purpose: the generator must never decide what counts as "the platform".
 * Keep in sync with the platform table in README.md.
 */
const TIER1 = [
  "wazoo-api",
  "worlds-api",
  "wazoo-console",
  "wazoo-desktop",
  "wazoo-client-ts",
  "worlds-client-ts",
  "worlds-sdk-ts",
  "worlds-kit",
  "sparql-engine",
  "wazoo-tools",
  "wazoo-cli",
  "wazoo-skills",
  "worlds-libsql",
  "worlds-sqlite",
  "worlds-postgres",
  "worlds-cloudflare",
  "worlds-indexeddb",
  "docs.wazoo.dev",
  "wazoo.dev",
];

/** Published packages, so VERSION.md can record what is actually installable. */
const PACKAGES = {
  "wazoo-api": null,
  "worlds-api": null,
  "wazoo-console": null,
  "wazoo-desktop": null,
  "wazoo-client-ts": "@wazoo/client",
  "worlds-client-ts": "@worlds/client",
  "worlds-sdk-ts": "@worlds/sdk",
  "worlds-kit": "@wazoo/worlds-kit",
  "sparql-engine": "@wazoo/sparql-engine",
  "wazoo-tools": "@wazoo/tools",
  "wazoo-cli": null,
  "wazoo-skills": null,
  "worlds-libsql": "@worlds/libsql",
  "worlds-sqlite": "@worlds/sqlite",
  "worlds-postgres": "@worlds/postgres",
  "worlds-cloudflare": "@worlds/cloudflare",
  "worlds-indexeddb": "@worlds/indexeddb",
  "docs.wazoo.dev": null,
  "wazoo.dev": null,
};

const BANNER = "<!-- generated by scripts/generate.mjs — do not edit by hand -->";
const TIMESTAMP = /^<!-- generated-at: .*-->$/m;
// Repositories the curated map depends on. Their absence means the listing
// itself is truncated, not that the organization lost repositories.
const ORG_SENTINELS = ["wazoo-api", "worlds-api", "docs.wazoo.dev", "wazoo-skills"];

function gh(args) {
  try {
    return execFileSync("gh", args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (error) {
    throw new Error(
      `gh ${args.join(" ")} failed: ${error.stderr?.toString().trim() || error.message}`,
    );
  }
}

function ghJson(args) {
  return JSON.parse(gh(args));
}

async function packageVersion(pkg) {
  if (!pkg) return null;
  try {
    const res = await fetch(`https://jsr.io/${pkg}/meta.json`, {
      headers: { accept: "application/json" },
    });
    if (!res.ok) return null;
    const meta = await res.json();
    return typeof meta.latest === "string" ? meta.latest : null;
  } catch {
    return null;
  }
}

async function listRepos() {
  const all = [];
  for (let page = 1; ; page++) {
    const batch = ghJson([
      "api",
      `orgs/${OWNER}/repos?per_page=100&page=${page}&type=all`,
    ]);
    if (!Array.isArray(batch) || batch.length === 0) break;
    all.push(...batch);
    if (batch.length < 100) break;
  }
  return all;
}

/**
 * Refuse to generate from a partial view of the organization.
 *
 * Note what is *not* a sufficient test: reading a single public repository.
 * Any token can do that, including a `GITHUB_TOKEN` scoped to this repository.
 * The capability that actually matters is the ability to *list* the
 * organization, which such a token cannot do — it returns this repository and
 * little else. So the listing itself is the sentinel: if repositories the
 * curated map depends on are absent from it, the list is truncated.
 */
function requireCompleteOrgListing(repos) {
  const names = new Set(repos.map((r) => r.name));
  const absent = ORG_SENTINELS.filter((n) => !names.has(n));
  if (absent.length === 0) return;

  console.error(
    `The organization listing is incomplete: ${absent.map((n) => `${OWNER}/${n}`).join(", ")}\n` +
      `not present. ${repos.length} repositories were visible, which is not the whole\n` +
      "organization. Generating from a partial view would produce an inventory\n" +
      "missing most of the platform, and --check would then blame the committed\n" +
      "file for being stale.\n\n" +
      "Fix: give the workflow a token with read access to the organization, as the\n" +
      "GH_ORG_TOKEN secret. A GITHUB_TOKEN scoped to this repository is not enough.",
  );
  process.exit(2);
}

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const INSTALL_BEGIN = "<!-- versions-table: generated by scripts/generate.mjs — do not edit by hand -->";
const INSTALL_END = "<!-- /versions-table -->";

async function renderInstallTable(repos) {
  const byName = new Map(repos.map((r) => [r.name, r]));
  const rows = [];
  for (const name of INSTALL_PACKAGES) {
    const pkg = PACKAGES[name] ?? null;
    const version = pkg ? await packageVersion(pkg) : null;
    const repo = byName.get(name);
    const repoCell = repo
      ? `[${name}](https://github.com/${OWNER}/${name})`
      : name;
    rows.push(
      `| \`${pkg}\` | JSR | ${version ?? "_unpublished_"} | ${repoCell} |`,
    );
  }
  return [
    INSTALL_BEGIN,
    "",
    "| Package | Registry | Latest | Repository |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    INSTALL_END,
  ].join("\n");
}

/**
 * Replace (or seed) the generated region in INSTALL.md. Everything outside
 * the markers is handwritten and untouched.
 */
function applyInstallTable(content, table) {
  const begin = content.indexOf(INSTALL_BEGIN);
  const end = content.indexOf(INSTALL_END);
  if (begin !== -1 && end !== -1) {
    return content.slice(0, begin) + table + content.slice(end + INSTALL_END.length);
  }
  if (begin !== -1 || end !== -1) {
    throw new Error("INSTALL.md has only one of the two versions-table markers");
  }
  // No markers yet: seed them in place of the first fenced table after the
  // "Or via CDN" section by appending at the end of the file is wrong —
  // instead, require the markers to exist. The one-time seeding is done by
  // hand in the same PR that adds generator support.
  throw new Error(
    "INSTALL.md is missing the versions-table markers; add them in the same change",
  );
}

function renderRepos(repos) {
  const publicRepos = repos.filter((r) => !r.private);
  const current = publicRepos.filter((r) => !r.archived).sort((a, b) => a.name.localeCompare(b.name));
  const archived = publicRepos.filter((r) => r.archived).sort((a, b) => a.name.localeCompare(b.name));

  const table = (rows) =>
    [
      "| Repository | What it is |",
      "| --- | --- |",
      ...rows.map(
        (r) =>
          `| [${r.name}](https://github.com/${OWNER}/${r.name}) | ${
            cell(r.description) || "_(no description)_"
          } |`,
      ),
    ].join("\n");

  return `${BANNER}
<!-- generated-at: ${new Date().toISOString()} -->

# Repository inventory

Every public repository in the \`${OWNER}\` organization: **${current.length} current**,
**${archived.length} archived**. Generated from the organization, so it is never
out of date by neglect.

Private repositories are omitted — this is a public map.

The count of them is deliberately absent. How many private repositories exist is
both unnecessary to a reader and not reproducible: it depends on whether the
generating credential can see private repositories at all, so the file would
differ between a maintainer's token and the workflow's, and \`--check\` would
report drift that does not exist.

The curated view of the platform — the ones worth reading first — is the table in
[README.md](README.md).

## Current (${current.length})

${table(current)}

## Archived (${archived.length})

Frozen. Linked for history, not for use.

${table(archived)}
`;
}

/**
 * INSTALL.md's version table. The prose around it is handwritten; the table
 * itself is generated between markers, so it can no longer drift from
 * VERSION.md or the registries. Order matches the prose's presentation:
 * SDK first, then the adapters, then the rest.
 */
const INSTALL_PACKAGES = [
  "worlds-sdk-ts",
  "worlds-libsql",
  "worlds-sqlite",
  "worlds-postgres",
  "worlds-cloudflare",
  "worlds-indexeddb",
  "sparql-engine",
  "wazoo-client-ts",
  "worlds-client-ts",
  "wazoo-tools",
];

async function renderVersion(repos) {
  const byName = new Map(repos.map((r) => [r.name, r]));
  const rows = [];

  for (const name of TIER1) {
    const repo = byName.get(name);
    if (!repo) {
      rows.push(`| ${name} | **not found in the organization** | — | — |`);
      continue;
    }
    const pkg = PACKAGES[name] ?? null;
    const version = await packageVersion(pkg);
    const state = repo.archived ? "archived" : repo.isEmpty ? "empty" : "current";
    rows.push(
      `| [${name}](https://github.com/${OWNER}/${name}) | ${state} | ${
        pkg ? `\`${pkg}\`` : "—"
      } | ${version ?? (pkg ? "_unpublished_" : "—")} |`,
    );
  }

  return `${BANNER}
<!-- generated-at: ${new Date().toISOString()} -->

# Versions

**This map does not pin a platform release.** There is no coherent cross-repo
release process for Wazoo yet — the repositories version and publish
independently. This file records what each part looked like when the map was
last regenerated; it is a record, not a lockfile. Do not treat two rows agreeing
as a supported combination.

## Map version

${MAP_VERSION} — the version of this map, not of the platform.

## Platform repositories

| Repository | State | Package | Latest |
| --- | --- | --- | --- |
${rows.join("\n")}

## Why there are no commit hashes

arsumbris pins one tag across every part of its system, so a version there is
meaningful. Wazoo has no equivalent, and writing commit hashes here would imply
a coherence that does not exist. Whether to adopt one is an open question, tracked
with the rest of this repository's upkeep decisions.
`;
}

async function main() {
    const check = process.argv.includes("--check");
    const repos = await listRepos();
    requireCompleteOrgListing(repos);
  const installPath = join(ROOT, "INSTALL.md");
  let installContent = "";
  try {
    installContent = readFileSync(installPath, "utf8");
  } catch {
    throw new Error("INSTALL.md not found");
  }
  const installTable = await renderInstallTable(repos);
  const outputs = [
    ["REPOS.md", renderRepos(repos)],
    ["VERSION.md", await renderVersion(repos)],
    ["INSTALL.md", applyInstallTable(installContent, installTable)],
  ];

  let stale = 0;
  for (const [name, content] of outputs) {
    const path = join(ROOT, name);
    if (!check) {
      writeFileSync(path, content, "utf8");
      console.log(`wrote ${name}`);
      continue;
    }
    let existing = "";
    try {
      existing = readFileSync(path, "utf8");
    } catch {
      /* missing file counts as stale */
    }
    // The timestamp is the only intentionally volatile line.
    if (existing.replace(TIMESTAMP, "") !== content.replace(TIMESTAMP, "")) {
      console.error(`stale: ${name} — run: node scripts/generate.mjs`);
      stale++;
    }
  }

  if (check) {
    if (stale > 0) {
      // Drift is a tracked state, not a failure: check-links.mjs --file-issue
      // delivers the signal to the drift issue, so exiting nonzero here would
      // paint every drift Monday red and bury the run where the radar actually
      // breaks. An exit code should mean "this tool is broken", not "the world
      // changed in a way the tool exists to report".
      console.error(
        `\nDRIFT: ${stale} generated file(s) out of date — tracked by the drift issue; run: node scripts/generate.mjs`,
      );
      process.exit(0);
    }
    console.log("generated files are up to date");
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
